CURSOR = "\x01"
GLYPH_H = 8
LINE_H = 10
SPACE_W = 3
TRACKING = 1


class BitmapFont:
    """Renders GLYPHS into cached, tinted pygame surfaces."""

    def __init__(self):
        self._masks = {}
        for ch, art in GLYPHS.items():
            rows = art.split("/")
            cols_used = [x for x in range(5) if any(r[x] == "#" for r in rows)]
            if not cols_used:
                self._masks[ch] = (None, SPACE_W)
                continue
            x0, x1 = cols_used[0], cols_used[-1]
            w = x1 - x0 + 1
            mask = pygame.Surface((w, GLYPH_H), pygame.SRCALPHA)
            for y, row in enumerate(rows):
                for x in range(x0, x1 + 1):
                    if row[x] == "#":
                        mask.set_at((x - x0, y), (255, 255, 255, 255))
            self._masks[ch] = (mask, w)
        self._cache = {}

    def char_width(self, ch):
        mask, w = self._masks.get(ch, self._masks["?"])
        return w

    def width(self, text):
        total = 0
        for ch in text:
            total += self.char_width(ch) + TRACKING
        return max(0, total - TRACKING)

    def _tinted(self, ch, color):
        key = (ch, color)
        surf = self._cache.get(key)
        if surf is None:
            mask, w = self._masks.get(ch, self._masks["?"])
            if mask is None:
                return None, w
            surf = mask.copy()
            surf.fill(color + (255,), special_flags=pygame.BLEND_RGBA_MULT)
            self._cache[key] = surf
        return surf, self.char_width(ch)

    def draw(self, dest, text, x, y, color=(32, 28, 44), shadow=None):
        """Draw a single line. Returns the x position after the last glyph."""
        if shadow is not None:
            self.draw(dest, text, x + 1, y + 1, shadow, None)
        cx = x
        for ch in text:
            surf, w = self._tinted(ch, color)
            if surf is not None:
                dest.blit(surf, (cx, y))
            cx += w + TRACKING
        return cx

    def draw_centered(self, dest, text, cx, y, color=(32, 28, 44), shadow=None):
        return self.draw(dest, text, cx - self.width(text) // 2, y, color, shadow)

    def wrap(self, text, max_w):
        """Greedy word wrap. Honours explicit '\\n' breaks."""
        lines = []
        for para in text.split("\n"):
            words = para.split(" ")
            cur = ""
            for word in words:
                trial = word if not cur else cur + " " + word
                if self.width(trial) <= max_w or not cur:
                    cur = trial
                else:
                    lines.append(cur)
                    cur = word
            lines.append(cur)
        return lines


_font = None


def get_font():
    global _font
    if _font is None:
        _font = BitmapFont()
    return _font
